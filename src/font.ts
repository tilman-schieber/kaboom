const GLYPHS: Record<string, [number, number][]> = {};
for (const [ch, rows] of Object.entries(G)) {
  const px: [number, number][] = [];
  rows.split('|').forEach((row, y) => [...row].forEach((c, x) => c === '#' && px.push([x, y])));
  GLYPHS[ch] = px;
}

export const textWidth = (s: string) => s.length * 6 - 1;

export function drawText(ctx: CanvasRenderingContext2D, s: string, x: number, y: number, color = '#fcfcfc') {
  ctx.fillStyle = color;
  for (let i = 0; i < s.length; i++) {
    const g = GLYPHS[s[i]] ?? GLYPHS[s[i].toUpperCase()] ?? GLYPHS[' '];
    for (const [px, py] of g) ctx.fillRect(x + i * 6 + px, y + py, 1, 1);
  }
}

export function drawTextCentered(ctx: CanvasRenderingContext2D, s: string, cx: number, y: number, color?: string) {
  drawText(ctx, s, Math.round(cx - textWidth(s) / 2), y, color);
}

/** Big text: every font pixel drawn as an s-by-s block. */
export function drawTextScaled(ctx: CanvasRenderingContext2D, s: string, x: number, y: number, scale: number, color = '#fcfcfc') {
  ctx.fillStyle = color;
  for (let i = 0; i < s.length; i++) {
    const g = GLYPHS[s[i]] ?? GLYPHS[s[i].toUpperCase()] ?? GLYPHS[' '];
    for (const [px, py] of g) ctx.fillRect(x + (i * 6 + px) * scale, y + py * scale, scale, scale);
  }
}

/** Text with a one-pixel black drop shadow, readable over the terrain. */
export function drawTextShadow(ctx: CanvasRenderingContext2D, s: string, x: number, y: number, color = '#fcfcfc') {
  drawText(ctx, s, x + 1, y + 1, '#000');
  drawText(ctx, s, x, y, color);
}
